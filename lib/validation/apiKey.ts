/**
 * The one zod schema for API Key, shared by form and Server Action.
 *
 * FROZEN CONTRACT (Wave 1). Mirrors `public.api_keys`: `nama_konsumen`
 * NOT NULL, `allowed_fields` `text[]` NOT NULL DEFAULT '{}', `status` CHECK IN
 * ('aktif','nonaktif').
 *
 * The one rule the database cannot state is the important one: every entry of
 * `allowed_fields` must be a column of `v_employees_api`, whose column list is
 * the universe of what a Konsumen may ever ask for (ADR-004). That list is
 * generated from the database itself (`API_EMPLOYEE_FIELDS`), so a whitelist
 * can never name a column that does not exist — or one of the Data Pribadi
 * Sensitif columns, which are absent from that view by construction.
 *
 * `key_prefix` and `key_hash` are never accepted from a form: the key is
 * generated server-side, shown once, and only its SHA-256 is stored
 * (API-CONTRACT.md §Auth).
 */
import { z } from "zod";

import { API_EMPLOYEE_FIELDS } from "@/lib/schema/columns.generated";

import { requiredText, statusSchema, uuidField } from "./common";

/** Every column a Konsumen may be granted — the `v_employees_api` column list. */
export const ALLOWED_FIELD_VALUES: readonly string[] = API_EMPLOYEE_FIELDS;

/** `hck_` + 40 random characters (API-CONTRACT.md §Auth). */
export const API_KEY_PREFIX = "hck_";
export const API_KEY_PATTERN = /^hck_[A-Za-z0-9]{40}$/;

const allowedFieldSchema = z
  .string()
  .refine((field) => ALLOWED_FIELD_VALUES.includes(field), {
    error: "Kolom tidak tersedia di v_employees_api.",
  });

export const apiKeyFieldsSchema = z.object({
  nama_konsumen: requiredText("Nama Konsumen", 255),
  allowed_fields: z
    .array(allowedFieldSchema, { error: "Daftar kolom tidak valid." })
    .min(1, { error: "Pilih minimal satu kolom yang boleh diambil." })
    // A duplicate entry is harmless in the database but makes the UI lie about
    // how many columns a Konsumen has; normalise instead of rejecting.
    .transform((fields) => [...new Set(fields)]),
  status: statusSchema.default("aktif"),
});

/** Buat API Key baru (PRD #19). The key itself is generated by the action. */
export const apiKeyCreateSchema = apiKeyFieldsSchema;

/** Ubah API Key: nama, whitelist, atau status. */
export const apiKeyUpdateSchema = apiKeyFieldsSchema
  .partial()
  // `status` without its default — see the note in `lib/validation/employee.ts`.
  // `allowed_fields` carries no default either: an omitted whitelist means
  // "biarkan seperti sekarang", never "grant nothing".
  .extend({ id: uuidField("API Key"), status: statusSchema.optional() });

/** Nonaktifkan / aktifkan kembali satu key (PRD #19, #20). */
export const apiKeySetStatusSchema = z.object({
  id: uuidField("API Key"),
  status: statusSchema,
});

/** The Bearer token a Konsumen sends (API-CONTRACT.md §Auth). */
export const apiKeyTokenSchema = z
  .string()
  .regex(API_KEY_PATTERN, { error: "Format API Key tidak dikenal." });

export type ApiKeyFields = z.infer<typeof apiKeyFieldsSchema>;
export type ApiKeyCreateInput = z.infer<typeof apiKeyCreateSchema>;
export type ApiKeyUpdateInput = z.infer<typeof apiKeyUpdateSchema>;
export type ApiKeySetStatusInput = z.infer<typeof apiKeySetStatusSchema>;
